#!/usr/bin/env bash
#
# ChatterMate — update an install created by install.sh.
# Pulls the latest code, installs new dependencies, runs migrations,
# rebuilds the frontend + widget, and restarts the backend.
#
#   sudo bash /opt/chattermate/update.sh
#
# Run from anywhere; it finds the repo from its own location. Safe to re-run.
# It refuses to pull over uncommitted local changes unless --force is given
# (which discards them with `git reset --hard`). backend/.env is never touched
# except for URL lines, which follow the public URL in .install-state.
#
set -euo pipefail

FORCE=0
while [ $# -gt 0 ]; do
    case "$1" in
        --force) FORCE=1; shift ;;
        --help|-h) sed -n '2,12p' "$0" | sed 's/^# \?//'; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
done

[ "$(id -u)" -eq 0 ] || { echo "Run as root (or with sudo): sudo bash $0" >&2; exit 1; }

INSTALL_DIR="$(cd "$(dirname "$0")" && pwd)"
APP_USER="chattermate"
BRANCH="$(git -C "$INSTALL_DIR" rev-parse --abbrev-ref HEAD 2>/dev/null || echo main)"
if [ "$BRANCH" = "HEAD" ]; then
    echo "Detached HEAD in $INSTALL_DIR — check out a branch first (git checkout main)" >&2
    exit 1
fi

say() { printf '\n==> %s\n' "$*"; }
die() { printf '\n✗ ERROR: %s\n' "$*" >&2; exit 1; }

# Same template renderer as install.sh (Python, not sed: values containing
# &, #, \ or / would corrupt a sed replacement string).
render_template() {
    local src="$1" dest="$2"; shift 2
    python3 - "$src" "$dest" "$@" <<'PY'
import sys
src, dest, pairs = sys.argv[1], sys.argv[2], sys.argv[3:]
text = open(src).read()
for i in range(0, len(pairs), 2):
    text = text.replace("__%s__" % pairs[i], pairs[i + 1])
open(dest, "w").write(text)
PY
}

cd "$INSTALL_DIR"
say "Updating ChatterMate in $INSTALL_DIR (branch $BRANCH)"
# The build regenerates these TRACKED files, so restore exactly them before
# the dirty check — anything else dirty is a real operator edit.
git checkout -- frontend/public/config.js backend/assets/widget.js backend/assets/widget.css 2>/dev/null || true
if [ "$(git status --porcelain | grep -v '^??' | head -1)" ] && [ "$FORCE" -eq 0 ]; then
    die "uncommitted changes in $INSTALL_DIR — commit/stash them, or re-run with --force (their changes will be lost)"
fi
git fetch origin
git checkout "$BRANCH"
if [ "$FORCE" -eq 1 ]; then
    git reset --hard "origin/$BRANCH"
else
    git pull --ff-only origin "$BRANCH"
fi
echo "  ✓ code is now $(git rev-parse --short HEAD)"

say "Installing backend dependencies + running migrations"
sudo -u "$APP_USER" "$INSTALL_DIR/backend/venv/bin/pip" install -q -r "$INSTALL_DIR/backend/requirements.txt"
sudo -u "$APP_USER" bash -c "cd '$INSTALL_DIR/backend' && './venv/bin/alembic' upgrade head"
echo "  ✓ migrations applied"

say "Rebuilding frontend + widget"
# Regenerate .env.prod from the recorded public URL so the build bakes in the
# right API/WS/widget origins even if install.sh was last run with another one.
PUBLIC_URL="$(grep -E '^public_url=' "$INSTALL_DIR/.install-state" 2>/dev/null | cut -d= -f2 || true)"
if [ -n "$PUBLIC_URL" ]; then
    PUBLIC_HOST="${PUBLIC_URL#*://}"
    case "$PUBLIC_URL" in https://*) WS_SCHEME="wss" ;; *) WS_SCHEME="ws" ;; esac
    cat > "$INSTALL_DIR/frontend/.env.prod" <<EOF
# Generated by update.sh — public URLs for this install.
VITE_API_URL=$PUBLIC_URL/api/v1
VITE_WS_URL=$WS_SCHEME://$PUBLIC_HOST
VITE_WIDGET_URL=$PUBLIC_URL
EOF
    chown "$APP_USER:$APP_USER" "$INSTALL_DIR/frontend/.env.prod"
fi
cd "$INSTALL_DIR/frontend"
if [ ! -d node_modules ] || [ package-lock.json -nt node_modules ]; then
    sudo -u "$APP_USER" npm ci --no-audit --no-fund
fi
sudo -u "$APP_USER" npm run build:prod
sudo -u "$APP_USER" npm run build:widget:prod
[ -f "$INSTALL_DIR/backend/assets/widget.js" ] || die "widget bundle missing after build"
chown -R "$APP_USER:$APP_USER" "$INSTALL_DIR/frontend/dist" "$INSTALL_DIR/backend/assets"
echo "  ✓ frontend + widget rebuilt"

# Refresh the nginx site from the repo template — but never when certbot
# manages it (a certificate exists): rewriting would wipe the 443 block.
if [ -n "${PUBLIC_HOST:-}" ] && [ ! -f "/etc/letsencrypt/live/$PUBLIC_HOST/fullchain.pem" ]; then
    render_template "$INSTALL_DIR/deploy/nginx/chattermate.conf.template" \
        /etc/nginx/sites-available/chattermate \
        PUBLIC_HOST "$PUBLIC_HOST" INSTALL_DIR "$INSTALL_DIR"
    echo "  ✓ nginx site refreshed"
fi

# Record the new build so a later install.sh re-run can skip rebuilding.
NEW_COMMIT="$(git -C "$INSTALL_DIR" rev-parse HEAD)"
if [ -f "$INSTALL_DIR/.install-state" ]; then
    if grep -q '^built_commit=' "$INSTALL_DIR/.install-state"; then
        sed -i "s/^built_commit=.*/built_commit=$NEW_COMMIT/" "$INSTALL_DIR/.install-state"
    else
        echo "built_commit=$NEW_COMMIT" >> "$INSTALL_DIR/.install-state"
    fi
fi

say "Restarting services"
systemctl restart chattermate-backend
nginx -t && systemctl reload-or-restart nginx

say "Waiting for the backend to answer"
for _ in $(seq 1 60); do
    curl -fsS -m 3 http://127.0.0.1:8000/health >/dev/null 2>&1 && break
    sleep 2
done
curl -fsS -m 5 http://127.0.0.1:8000/health >/dev/null \
    || die "backend did not become healthy — see: journalctl -u chattermate-backend -n 100"

echo
echo "ChatterMate updated and healthy."
[ -n "${PUBLIC_URL:-}" ] && echo "App: $PUBLIC_URL/"
